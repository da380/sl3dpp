"""Present-day Earth state for the examples: ICE-7G ice thickness and
topography (sea level), dumped as real spherical-harmonic coefficients to
lmax 256 so the example drivers can synthesise them on their own grids at
any resolution up to that.

The ICE-7G and ETOPO data are pyslfp's: it downloads them from Zenodo on
first use and caches them (under ~/.pyslfp_data unless PYSLFP_DATA says
otherwise). Run in this directory's environment (pyproject.toml):

    cd scripts && poetry install --no-root
    poetry run python make_example_earth_state.py --out <path>

examples/CMakeLists.txt also runs it as part of the build, writing into the
build tree, in the environment of a pyslfp checkout when it finds one
(SL3DPP_PYSLFP_DIR).
"""
from __future__ import annotations

import argparse
import datetime
import pathlib

from pyslfp.ice.ice_ng import IceNG

LMAX = 256


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=pathlib.Path,
                        default=pathlib.Path("earth_state_l256.txt"))
    out = parser.parse_args().out
    model = IceNG(version="ICE7G")
    ice, sea_level = model.get_ice_thickness_and_sea_level(
        0.0, LMAX, grid="GLQ", extend=False)
    ice_lm = ice.expand(normalization="ortho", csphase=1).coeffs
    sl_lm = sea_level.expand(normalization="ortho", csphase=1).coeffs

    lines = [
        "# present-day Earth state for the sl3dpp examples, generated by "
        "scripts/make_example_earth_state.py",
        f"# ICE-7G at 0 ka via pyslfp (GLQ, lmax {LMAX}), "
        f"{datetime.date.today().isoformat()}",
        "# rows: 'l m ice_cos ice_sin sl_cos sl_sin' — real orthonormal "
        "SH, NO Condon-Shortley phase, SI metres; ice thickness and sea "
        "level (topography is minus the sea level over land)",
        f"lmax {LMAX}",
    ]
    for l in range(LMAX + 1):
        for m in range(l + 1):
            lines.append(
                f"{l} {m} {ice_lm[0, l, m]:.8e} {ice_lm[1, l, m]:.8e} "
                f"{sl_lm[0, l, m]:.8e} {sl_lm[1, l, m]:.8e}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(lines)} lines)")


if __name__ == "__main__":
    main()
