"""Generalised Love numbers of a PREM deck, from pyslfp.

Samples PREM (no ocean) to an elastic deck, reads that file back with
planetmodel, and records pyslfp's Love numbers on the uniform lmax mesh
rule — the same rule sl3dpp's RadialMesh implements — so both codes solve
the identical discrete problem and agreement is expected near machine
precision. tests/TestFixtures.cpp holds the C++ to it, and the sea-level
fixtures use the table as their Love numbers.

Run in this directory's environment (pyproject.toml):

    cd scripts && poetry install --no-root
    poetry run python make_love_number_fixtures.py [--data-dir DIR]

Outputs (committed): tests/data/prem8.elastic.deck,
tests/data/pyslfp_love_numbers.txt
"""
from __future__ import annotations

import numpy as np
from planetmodel import (PREM, Deck, DeckFormat, Geometry, Model, RadialMesh,
                         deck_layers, read_deck, write_deck)
from pyslfp.love_numbers import fluid_tidal_number, love_numbers
from pyslfp.love_numbers.table import NAMES

from fixture_tools import data_dir, provenance

KNOTS_PER_LAYER = 8
LMAX = 32
ELASTIC = DeckFormat(("rho", "vpv", "vsv", "vph", "vsh", "eta"),
                     name="elastic")


def main() -> None:
    data = data_dir(__doc__)
    prem = PREM(ocean=False)

    radius, columns = [], {name: [] for name in ELASTIC.columns}
    for layer in prem.layers:
        lo, hi = layer.interval
        r = np.linspace(lo, hi, KNOTS_PER_LAYER)
        radius.append(r)
        for name in ELASTIC.columns:
            if name in layer:
                columns[name].append(np.asarray(layer[name](r), dtype=float))
            elif name == "eta":
                columns[name].append(np.ones(r.size))
            elif name in ("vph", "vsh"):
                base = "vpv" if name == "vph" else "vsv"
                columns[name].append(np.asarray(layer[base](r), dtype=float))
            else:
                raise KeyError(f"layer {layer.index} lacks {name}")
    deck = Deck(np.concatenate(radius),
                {n: np.concatenate(v) for n, v in columns.items()})
    deck_path = write_deck(data / "prem8.elastic.deck", deck, ELASTIC)

    filed = read_deck(deck_path, ELASTIC)
    skeleton, layers = deck_layers(filed, kind="cubic")
    model = Model(Geometry(skeleton), layers)
    mesh = RadialMesh(model, lmax=LMAX, ngll=5)
    ln = love_numbers(model, LMAX, mesh=mesh)
    k_hyd = fluid_tidal_number(model, 2, mesh=mesh)

    lines = [
        "# Love-number reference, generated by "
        "scripts/make_love_number_fixtures.py",
        f"# {provenance('pyslfp', 'planetmodel')}",
        "# model: tests/data/prem8.elastic.deck (SI), cubic (not-a-knot); "
        f"mesh: uniform lmax={LMAX} rule, ngll=5, eps=1e-8",
        "# all values SI; columns: " + " ".join(("l",) + NAMES),
        f"radius {ln.radius:.17g}",
        f"surface_gravity {ln.surface_gravity:.17g}",
        f"axial {ln.h_c:.17g} {ln.k_c:.17g} {ln.m_u:.17g} "
        f"{ln.m_phi:.17g} {ln.m_c:.17g}",
        f"fluid_tidal_2 {k_hyd:.17g}",
        "table",
    ]
    for l in range(LMAX + 1):
        row = [f"{l}"] + [f"{getattr(ln, n)[l]:.17g}" for n in NAMES]
        lines.append(" ".join(row))
    (data / "pyslfp_love_numbers.txt").write_text("\n".join(lines) + "\n")
    print(f"wrote {deck_path} and {data / 'pyslfp_love_numbers.txt'}")
    print(f"k_hyd(2) {k_hyd:.12g}, h_u(2) {ln.h_u[2]:.12e}, "
          f"reciprocity {np.max(ln.reciprocity_residual()):.3g}")


if __name__ == "__main__":
    main()
