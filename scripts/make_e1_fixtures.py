"""E1 fixtures: non-gravitating and gravitating traction numbers from pyslfp.

The E1 tier of the cross-code benchmark hierarchy compares the elastic
response to unit surface tractions, without and with gravity, on solid
spherical models.  This script writes two solid decks -- the homogeneous
and two-solid models of AdGIA's benchmark ladder
(`AdGIA/benchmarks/common/models.py`), full precision -- reads each back
with planetmodel, and records pyslfp's traction numbers on the uniform
lmax mesh rule, the same rule sl3dpp's RadialMesh implements, so both
codes solve the identical discrete problem and agreement is expected
near machine precision. tests/TestTractionNumbers.cpp holds the C++ to
it.

Run in this directory's environment (pyproject.toml):

    cd scripts && poetry install --no-root
    poetry run python make_e1_fixtures.py [--data-dir DIR]

Outputs (committed): tests/data/e1_homogeneous.deck,
tests/data/e1_two_solid.deck, tests/data/e1_traction_numbers.txt
"""
from __future__ import annotations

import numpy as np
from planetmodel import (Deck, DeckFormat, Geometry, LayeredIsotropicElastic,
                         Model, RadialMesh, deck_layers, read_deck,
                         write_deck)
from pyslfp.love_numbers import traction_numbers

from fixture_tools import data_dir, provenance

KNOTS_PER_LAYER = 8
LMAX = 8


def full_precision(deck, names):
    rows = np.column_stack([deck.radius] + [deck[n] for n in names])
    return [" ".join(f"{v:.17g}" for v in row) for row in rows]


ELASTIC = DeckFormat(("rho", "vpv", "vsv", "vph", "vsh", "eta"),
                     name="elastic", write_table=full_precision)

#: The solid models of AdGIA's benchmark ladder, by their ladder names.
MODELS = {
    "homogeneous": LayeredIsotropicElastic(
        [0.0, 6371.0e3], rho=[5500.0], vp=[10000.0], vs=[5500.0],
        layer_names=["body"], interface_names=["surface"],
        name="homogeneous"),
    "two_solid": LayeredIsotropicElastic(
        [0.0, 5000.0e3, 6371.0e3], rho=[6500.0, 3500.0],
        vp=[12000.0, 8500.0], vs=[6500.0, 4500.0],
        layer_names=["lower", "upper"],
        interface_names=["discontinuity", "surface"], name="two_solid"),
}


def as_deck(model: Model) -> Deck:
    radius, columns = [], {name: [] for name in ELASTIC.columns}
    for layer in model.layers:
        lo, hi = layer.interval
        r = np.linspace(lo, hi, KNOTS_PER_LAYER)
        radius.append(r)
        for name in ELASTIC.columns:
            if name in layer:
                columns[name].append(np.asarray(layer[name](r), dtype=float))
            elif name == "eta":
                columns[name].append(np.ones(r.size))
            else:
                base = {"vpv": "vp", "vsv": "vs", "vph": "vp",
                        "vsh": "vs"}[name]
                columns[name].append(np.asarray(layer[base](r), dtype=float))
    return Deck(np.concatenate(radius),
                {n: np.concatenate(v) for n, v in columns.items()})


def main() -> None:
    data = data_dir(__doc__)
    lines = [
        "# E1 traction-number reference, generated by "
        "scripts/make_e1_fixtures.py",
        f"# {provenance('pyslfp', 'planetmodel')}",
        f"# mesh: uniform lmax={LMAX} rule, ngll=5, eps=1e-8; all values "
        "SI (m per Pa); NaN = excluded degree",
        "# per model and problem: columns l h_u l_u h_v l_v",
    ]
    for name, si in MODELS.items():
        deck_path = write_deck(data / f"e1_{name}.deck", as_deck(si), ELASTIC)
        skeleton, layers = deck_layers(read_deck(deck_path, ELASTIC),
                                       kind="cubic")
        model = Model(Geometry(skeleton), layers)
        mesh = RadialMesh(model, lmax=LMAX, ngll=5)
        for gravitating in (False, True):
            tn = traction_numbers(model, LMAX, gravitating=gravitating,
                                  mesh=mesh)
            lines.append(
                f"model {name} gravitating {int(gravitating)} "
                f"radius {tn.radius:.17g}")
            lines.append("table")
            for l in range(LMAX + 1):
                row = [f"{l}"] + [f"{getattr(tn, c)[l]:.17g}"
                                  for c in ("h_u", "l_u", "h_v", "l_v")]
                lines.append(" ".join(row))
        print(f"wrote {deck_path}")
    out = data / "e1_traction_numbers.txt"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
