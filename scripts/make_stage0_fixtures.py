"""Stage-0 fixtures: reference gravity from planetmodel (plan §6).

Samples PREM's density to a deck file, then reads that file back with
planetmodel and records its mass, moment of inertia and gravity. The deck
file itself is the fixture model: sl3dpp's tests read the same file, so
both codes interpolate identical knots (cubic / not-a-knot) and the
comparison is free of sampling skew.

Run from the planetmodel checkout, which owns the Python environment:

    cd ~/dev/planetmodel && poetry run python \
        ~/dev/sl3dpp/scripts/make_stage0_fixtures.py

Outputs (committed): tests/data/prem8.rho.deck, tests/data/stage0_gravity.txt
"""
from __future__ import annotations

import datetime
import pathlib
import subprocess

import numpy as np
from planetmodel import (PREM, Deck, DeckFormat, Geometry, Model, deck_layers,
                         read_deck, write_deck)
from planetmodel.layerfunction import polynomial_layer
from planetmodel.fields import RadialField
from planetmodel.mesh1d.gravity import gravity, mass

DATA = pathlib.Path(__file__).resolve().parent.parent / "tests" / "data"
KNOTS_PER_LAYER = 8
RHO_ONLY = DeckFormat(("rho",), name="rho-only")


def moment_of_inertia(model: Model) -> float:
    """(8 pi / 3) int rho s^4 ds, exactly, through the field algebra."""
    total = 0.0
    for layer in model.layers:
        lo, hi = layer.interval
        s4 = RadialField((lo, hi), polynomial_layer((lo, hi), [0, 0, 0, 0, 1]))
        total += float((layer["rho"] * s4).integrate(lo, hi))
    return (8.0 * np.pi / 3.0) * total


def main() -> None:
    prem = PREM()

    # Sample the density to a deck and write it (the fixture model).
    radius, rho = [], []
    for layer in prem.layers:
        lo, hi = layer.interval
        r = np.linspace(lo, hi, KNOTS_PER_LAYER)
        radius.append(r)
        rho.append(np.asarray(layer["rho"](r), dtype=float))
    deck = Deck(np.concatenate(radius), {"rho": np.concatenate(rho)})
    deck_path = write_deck(DATA / "prem8.rho.deck", deck, RHO_ONLY)

    # Read it back and build the reference model from the file's numbers.
    filed = read_deck(deck_path, RHO_ONLY)
    skeleton, layers = deck_layers(filed, kind="cubic")
    model = Model(Geometry(skeleton), layers)

    b = skeleton.boundaries
    # planetmodel answers gravity inside the body only; the exterior is
    # covered by sl3dpp's analytic tests.
    radii = np.unique(np.concatenate([
        b, 0.5 * (b[:-1] + b[1:]), [0.25 * b[-1], 0.75 * b[-1]]]))

    import planetmodel as pm
    pm_dir = pathlib.Path(pm.__file__).resolve().parent
    commit = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                            cwd=pm_dir, capture_output=True, text=True,
                            check=False).stdout.strip() or "unknown"

    g = gravity(model, radii)
    lines = [
        "# stage-0 gravity reference, generated by "
        "scripts/make_stage0_fixtures.py",
        f"# planetmodel commit {commit}, "
        f"{datetime.date.today().isoformat()}",
        "# model: tests/data/prem8.rho.deck (SI), cubic (not-a-knot) "
        "interpolation",
        "# mass and moment by exact field-algebra integrals; gravity in SI",
        f"mass {mass(model):.17g}",
        f"moment {moment_of_inertia(model):.17g}",
        "gravity",
    ]
    lines += [f"{r:.17g} {value:.17g}" for r, value in zip(radii, g)]
    (DATA / "stage0_gravity.txt").write_text("\n".join(lines) + "\n")
    print(f"wrote {deck_path} and {DATA / 'stage0_gravity.txt'}")
    print(f"mass {mass(model):.12e}  surface g {g[np.argmax(radii == b[-1])]:.9f}")


if __name__ == "__main__":
    main()
