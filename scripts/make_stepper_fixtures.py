"""The 1D viscoelastic stepper's reference, from pyslfp.

A Love-number history: the PREM-like elastic deck with a 1e21 Pa s Maxwell
mantle (solid layers fully inside [3480, 6151] km — the same rule as the
C++ tests), held under a unit surface-density load at every degree, stepped
with the exponential trapezoid and backward Euler at fixed dt. Grid-free,
so the comparison isolates the stepper and is expected near machine
precision. The step's effective Love numbers are recorded besides.
tests/TestFixtures.cpp holds the C++ to it.

Run in this directory's environment (pyproject.toml):

    cd scripts && poetry install --no-root
    poetry run python make_stepper_fixtures.py [--data-dir DIR]

Output (committed): tests/data/pyslfp_stepper.txt
"""
from __future__ import annotations

import numpy as np
from planetmodel import (Geometry, Model, RadialMesh, deck_layers, read_deck)
from planetmodel.deck import DeckFormat
from pyslfp.love_numbers.material import Material
from pyslfp.viscoelastic import Rheology, ViscoelasticOperator

from fixture_tools import data_dir, provenance

LMAX = 10
DEGREES = (2, 5, 10)
ETA = 1e21          # Pa s
DT = 3.15576e9      # 100 years, s
STEPS = 50
ELASTIC = DeckFormat(("rho", "vpv", "vsv", "vph", "vsh", "eta"),
                     name="elastic")


def main() -> None:
    data = data_dir(__doc__)
    deck = read_deck(data / "prem8.elastic.deck", ELASTIC)
    skeleton, layers = deck_layers(deck, kind="cubic")
    model = Model(Geometry(skeleton), layers)
    mesh = RadialMesh(model, lmax=LMAX, ngll=5)
    material = Material(mesh, model)

    b = skeleton.boundaries
    viscosity = {}
    for i, layer in enumerate(model.layers):
        fluid = np.all(np.asarray(layer["vsv"](np.linspace(*layer.interval, 3)))
                       == 0.0)
        if not fluid and b[i] >= 3.4799e6 and b[i + 1] <= 6.1511e6:
            viscosity[i] = ETA
    rheology = Rheology.maxwell(material, viscosity)
    op = ViscoelasticOperator(rheology, LMAX)

    def load(l, t):
        return np.array([1.0])  # unit surface density, SI

    lines = [
        "# stepper reference, generated by scripts/make_stepper_fixtures.py",
        f"# {provenance('pyslfp')}; model: "
        "tests/data/prem8.elastic.deck + 1e21 Pa s Maxwell mantle",
        f"# uniform lmax={LMAX} mesh rule, ngll=5; unit SI load held from "
        f"t=0; dt={DT:.6g} s, {STEPS} steps",
        "# history rows: t  then (U, phi) at degrees " + str(DEGREES),
        f"min_relaxation_time {rheology.min_relaxation_time():.17g}",
    ]
    for scheme in ("exponential_trapezoid", "backward_euler"):
        lines.append(f"scheme {scheme}")
        state = op.zero_state(ncols=1)
        solutions = op.solve_elastic(state, load=load)

        def row(t, sols):
            U = op.surface(sols, "U")
            phi = op.surface(sols, "phi")
            values = []
            for l in DEGREES:
                values += [U[l][0], phi[l][0]]
            return f"{t:.17g} " + " ".join(f"{v:.17g}" for v in values)

        lines.append(row(0.0, solutions))
        for n in range(STEPS):
            state, solutions = op.step(state, DT, scheme=scheme, load=load)
            lines.append(row(state.t, solutions))

    table = op.effective_love_numbers("exponential_trapezoid", DT)
    lines.append("effective_love h_u k_u h_t k_t")
    for l in range(LMAX + 1):
        lines.append(f"{l} {table.h_u[l]:.17g} {table.k_u[l]:.17g} "
                     f"{table.h_t[l]:.17g} {table.k_t[l]:.17g}")
    (data / "pyslfp_stepper.txt").write_text("\n".join(lines) + "\n")
    print(f"wrote pyslfp_stepper.txt; tau_min = "
          f"{rheology.min_relaxation_time():.6g} s, viscous layers "
          f"{sorted(viscosity)}")


if __name__ == "__main__":
    main()
