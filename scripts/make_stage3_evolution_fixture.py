"""Stage-3 coupled-evolution fixture: pyslfp's forward GIA run (plan §6).

The analytic test state with the PREM-deck Maxwell body (the stage-3
stepper's rheology rule), ice melting linearly in time, stepped by the
coupled loop with full rotational feedback. The sharp flotation ocean
function makes the solution grid-sensitive, so pyslfp's own DH-vs-GLQ
spread is measured here and printed; the C++ gate's tolerances are set to
it (see the stage-2 precedent in docs/plan.md §6).

Run from the pyslfp checkout:

    cd ~/dev/pyslfp && poetry run python \
        ~/dev/sl3dpp/scripts/make_stage3_evolution_fixture.py

Output (committed): tests/data/stage3_evolution.txt
"""
from __future__ import annotations

import datetime
import pathlib

import numpy as np
from planetmodel import (Geometry, Model, RadialMesh, deck_layers, read_deck,
                         units)
from planetmodel.deck import DeckFormat
from pyshtools import SHGrid
from pyslfp.core import EarthModel, EarthState
from pyslfp.ice import AnalyticalIceModel
from pyslfp.love_numbers.material import Material
from pyslfp.love_numbers.table import LoveNumbers
from pyslfp.viscoelastic import Rheology, SeaLevelEvolution, ViscoelasticOperator

DATA = pathlib.Path(__file__).resolve().parent.parent / "tests" / "data"
LMAX = 16
ETA = 1e21
YEAR = 3.15576e7
T_FINAL = 5000.0 * YEAR
NODES = 11
MELT_FRACTION = 0.1
ELASTIC = DeckFormat(("rho", "vpv", "vsv", "vph", "vsh", "eta"),
                     name="elastic")
POTENTIAL = units.LENGTH**2 * units.TIME**-2


def build(gridname: str):
    deck = read_deck(DATA / "prem8.elastic.deck", ELASTIC)
    skeleton, layers = deck_layers(deck, kind="cubic")
    model = Model(Geometry(skeleton), layers)
    mesh = RadialMesh(model, lmax=LMAX, ngll=5)
    material = Material(mesh, model)
    b = skeleton.boundaries
    viscosity = {}
    for i, layer in enumerate(model.layers):
        fluid = np.all(np.asarray(layer["vsv"](np.linspace(*layer.interval, 3)))
                       == 0.0)
        if not fluid and b[i] >= 3.4799e6 and b[i + 1] <= 6.1511e6:
            viscosity[i] = ETA
    rheology = Rheology.maxwell(material, viscosity)
    op = ViscoelasticOperator(rheology, LMAX)
    table = LoveNumbers.from_model(model, LMAX, mesh=mesh)
    extend = gridname == "DH"
    earth = EarthModel(LMAX, love_numbers=table, grid=gridname, extend=extend)
    ice_model = AnalyticalIceModel(length_scale=earth.parameters.length_scale)
    ice, sl = ice_model.get_ice_thickness_and_sea_level(
        0.0, LMAX, grid=earth.grid_name, sampling=earth.sampling,
        extend=earth.extend)
    state = EarthState(ice, sl, earth, exclude_caspian=False)
    evolution = SeaLevelEvolution(op, state)
    scales = earth.parameters.scales
    times_si = np.linspace(0.0, T_FINAL, NODES)
    times = times_si / scales.factor(units.TIME)

    def ice_load(t):
        fraction = -MELT_FRACTION * (t / times[-1])
        change = fraction * state.ice_thickness
        return state.direct_load_from_ice_thickness_change(change)

    snapshots, _ = evolution.run(times, ice_load, rotational_feedbacks=True,
                                 rtol=1e-11)
    length = scales.factor(units.LENGTH)
    out = []
    for t_si, snap in zip(times_si, snapshots):
        slc_si = earth.expand_field(snap.sea_level_change).coeffs * length
        omega_si = snap.angular_velocity_change / scales.factor(units.TIME)
        out.append((t_si, slc_si, omega_si))
    return out


def main() -> None:
    dh = build("DH")
    glq = build("GLQ")
    spread_slc = max(
        np.max(np.abs(a[1] - b[1])) / np.max(np.abs(a[1])) if np.max(
            np.abs(a[1])) > 0 else 0.0
        for a, b in zip(dh[1:], glq[1:]))
    axial = [(a[2][2], b[2][2]) for a, b in zip(dh[1:], glq[1:])]
    spread_axial = max(abs(a - b) / max(abs(a), 1e-300) for a, b in axial)
    print(f"pyslfp DH-vs-GLQ spread: slc coeffs {spread_slc:.3g}, "
          f"axial omega {spread_axial:.3g}")

    lines = [
        "# stage-3 coupled-evolution reference, generated by "
        "scripts/make_stage3_evolution_fixture.py",
        f"# pyslfp (GLQ grid), {datetime.date.today().isoformat()}; the "
        "stage-3 Maxwell body on the analytic state, linear melt",
        "# The sharp-coastline solution is grid-determined: pyslfp's own "
        f"DH-vs-GLQ spread here is slc {spread_slc:.3g}, axial omega "
        f"{spread_axial:.3g}. The GLQ reference coincides with sl3dpp's "
        "grid at this lmax, isolating implementation error; the spread "
        "above is the physical sensitivity.",
        "# per node: 'node t_si omega_x omega_y omega_z' then slc "
        "coefficient rows 'l m a b' (SI)",
    ]
    for node, (t_si, slc, omega) in enumerate(glq):
        lines.append(f"node {node} {t_si:.17g} "
                     + " ".join(f"{x:.17g}" for x in omega))
        for l in range(LMAX + 1):
            for m in range(l + 1):
                lines.append(f"{l} {m} {slc[0, l, m]:.17g} "
                             f"{slc[1, l, m]:.17g}")
    (DATA / "stage3_evolution.txt").write_text("\n".join(lines) + "\n")
    print("wrote stage3_evolution.txt")


if __name__ == "__main__":
    main()
