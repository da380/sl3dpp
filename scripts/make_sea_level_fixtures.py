"""The sea level equation's references, from pyslfp.

Two gates, compared in coefficient space and through grid-independent
functionals (never by matching grids):

A. The tight gate: a generalised solve in which every input is exactly
   band-limited — the direct, displacement and potential loads, the two
   response channels, an inertia-moment change, and a smooth ocean-function
   override — so the solution is grid-independent to spectral accuracy.
   Inputs are recorded as coefficients; both codes synthesise them on
   their own grids.

B. The loose gate: a true fingerprint on the shared analytic state, whose
   sharp flotation ocean function makes the solution sensitive to each
   grid's coastline quadrature. Documented as such and compared coarsely.

Both take their Love numbers from the committed Love-number fixture
(tests/data/pyslfp_love_numbers.txt), so the sea level equation is
compared apart from the radial solver. tests/TestFixtures.cpp holds the
C++ to them.

Run in this directory's environment (pyproject.toml):

    cd scripts && poetry install --no-root
    poetry run python make_sea_level_fixtures.py [--data-dir DIR]

Outputs (committed): tests/data/pyslfp_generalised_sea_level.txt,
tests/data/pyslfp_fingerprint.txt
"""
from __future__ import annotations

import pathlib

import numpy as np
from planetmodel import units
from pyshtools import SHCoeffs, SHGrid
from pyslfp.core import EarthModel, EarthState, SeaLevelEquation
from pyslfp.ice import AnalyticalIceModel
from pyslfp.love_numbers.table import NAMES, LoveNumbers

from fixture_tools import data_dir, provenance

LMAX = 32

SURFACE_DENSITY = units.DENSITY * units.LENGTH
POTENTIAL = units.LENGTH**2 * units.TIME**-2
MOMENT = units.MASS * units.LENGTH**2


def read_love_table(path: pathlib.Path) -> LoveNumbers:
    """The Love-number fixture as a pyslfp LoveNumbers table (SI)."""
    radius = gravity = None
    axial = [np.nan] * 5
    rows = []
    in_table = False
    for line in path.read_text().splitlines():
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if not in_table:
            if parts[0] == "radius":
                radius = float(parts[1])
            elif parts[0] == "surface_gravity":
                gravity = float(parts[1])
            elif parts[0] == "axial":
                axial = [float(x) for x in parts[1:6]]
            elif parts[0] == "table":
                in_table = True
            continue
        rows.append([float(x) for x in parts])
    table = np.array(rows)
    columns = {name: table[:, j + 1] for j, name in enumerate(NAMES)}
    return LoveNumbers(
        table[:, 0].astype(int), *(columns[n] for n in NAMES), radius,
        gravity, units.G_SI, h_c=axial[0], k_c=axial[1], m_u=axial[2],
        m_phi=axial[3], m_c=axial[4])


def cap(lats, lons, colat0, lon0, width, power=2):
    colat = np.deg2rad(90.0 - lats)
    lon = np.deg2rad(lons)
    c = (np.cos(colat) * np.cos(colat0)
         + np.sin(colat) * np.sin(colat0) * np.cos(lon - lon0))
    d = np.arccos(np.clip(c, -1.0, 1.0))
    return np.exp(-0.5 * (d / width) ** power)


def band_limited(model: EarthModel, data: np.ndarray) -> SHCoeffs:
    """The field's expansion: synthesising it back gives an exactly
    band-limited field on any grid."""
    grid = SHGrid.from_array(data, grid=model.grid, copy=False)
    return model.expand_field(grid)


def write_coefficients(lines: list[str], name: str, clm: SHCoeffs,
                       factor: float) -> None:
    """One coefficient block, SI (values multiplied by `factor`)."""
    lines.append(f"field {name}")
    c = clm.coeffs
    for l in range(LMAX + 1):
        for m in range(l + 1):
            lines.append(f"{l} {m} {c[0, l, m] * factor:.17g} "
                         f"{c[1, l, m] * factor:.17g}")


def main() -> None:
    data = data_dir(__doc__)
    table = read_love_table(data / "pyslfp_love_numbers.txt")
    model = EarthModel(LMAX, love_numbers=table)
    sle = SeaLevelEquation(model)
    scales = model.parameters.scales
    lats, lons = np.meshgrid(model.lats(), model.lons(), indexing="ij")

    header = [
        "# sea-level references, generated by "
        "scripts/make_sea_level_fixtures.py",
        f"# {provenance('pyslfp')}; Love table: "
        "tests/data/pyslfp_love_numbers.txt",
        "# coefficients in the real orthonormal no-CS (pyshtools) basis, SI",
    ]

    # ---- Gate A: the generalised solve, every input band-limited ----------
    def nd_grid(clm: SHCoeffs, factor: float) -> SHGrid:
        out = model.expand_coefficient(clm)
        out.data /= factor
        return out

    si = {
        "ocean_function": band_limited(
            model, 1.0 - 0.85 * cap(lats, lons, 0.4, 0.3, 0.8)),
        "direct_load": band_limited(
            model, 120.0 * cap(lats, lons, 0.7, 1.0, 0.6)),
        "displacement_load": band_limited(
            model, 40.0 * cap(lats, lons, 1.9, 4.2, 0.7)),
        "potential_load": band_limited(
            model, -60.0 * cap(lats, lons, 1.1, 2.6, 0.9)),
        "displacement_response": band_limited(
            model, 0.4 * cap(lats, lons, 2.3, 5.0, 0.8)),
        "potential_response": band_limited(
            model, -2.5 * cap(lats, lons, 0.9, 3.6, 1.0)),
    }
    inertia_moment_si = 2.0e25  # kg m^2
    angular_momentum_si = np.array([1.0e24, -2.0e24, 3.0e24])  # kg m^2 / s

    sigma = scales.factor(SURFACE_DENSITY)
    slc, disp, phi, omega = sle.solve_generalised_equation(
        EarthState.for_testing(LMAX),  # unused: the ocean function is given
        direct_load=nd_grid(si["direct_load"], sigma),
        displacement_load=nd_grid(si["displacement_load"], sigma),
        gravitational_potential_load=nd_grid(si["potential_load"], sigma),
        displacement_response=SHCoeffs.from_array(
            si["displacement_response"].coeffs / scales.factor(units.LENGTH),
            normalization="ortho", csphase=1),
        gravitational_potential_response=SHCoeffs.from_array(
            si["potential_response"].coeffs / scales.factor(POTENTIAL),
            normalization="ortho", csphase=1),
        inertia_moment_change=inertia_moment_si / scales.factor(MOMENT),
        angular_momentum_change=angular_momentum_si
        / scales.factor(MOMENT * units.TIME**-1),
        ocean_function=nd_grid(si["ocean_function"], 1.0),
        rotational_feedbacks=True,
        rtol=1e-13,
    )

    lines = list(header)
    lines.append(f"inertia_moment {inertia_moment_si:.17g}")
    lines.append("angular_momentum "
                 + " ".join(f"{x:.17g}" for x in angular_momentum_si))
    for name, clm in si.items():
        # inputs stay in their SI units (the loads kg m^-2, the responses
        # m and m^2 s^-2, the ocean function unitless): recorded as given
        write_coefficients(lines, name, clm, 1.0)
    length = scales.factor(units.LENGTH)
    write_coefficients(lines, "sea_level_change", model.expand_field(slc),
                       length)
    write_coefficients(lines, "displacement", model.expand_field(disp), length)
    write_coefficients(lines, "potential", model.expand_field(phi),
                       scales.factor(POTENTIAL))
    omega_si = omega * scales.factor(units.TIME**-1)
    lines.append("omega " + " ".join(f"{x:.17g}" for x in omega_si))
    (data / "pyslfp_generalised_sea_level.txt").write_text(
        "\n".join(lines) + "\n")

    # ---- Gate B: the sharp-ocean fingerprint on the analytic state --------
    ice_model = AnalyticalIceModel(
        length_scale=model.parameters.length_scale)
    ice, sea_level = ice_model.get_ice_thickness_and_sea_level(
        0.0, LMAX, grid=model.grid_name, sampling=model.sampling,
        extend=model.extend)
    state = EarthState(ice, sea_level, model, exclude_caspian=False)
    ice_change = -0.1 * state.ice_thickness
    load = state.direct_load_from_ice_thickness_change(ice_change)
    slc, disp, phi, omega = sle.solve_sea_level_equation(
        state, load, rotational_feedbacks=True, rtol=1e-11)

    lines = list(header)
    lines.append(f"ocean_area {state.ocean_area * length**2:.17g}")
    write_coefficients(lines, "sea_level_change", model.expand_field(slc),
                       length)
    write_coefficients(lines, "displacement", model.expand_field(disp), length)
    write_coefficients(lines, "potential", model.expand_field(phi),
                       scales.factor(POTENTIAL))
    omega_si = omega * scales.factor(units.TIME**-1)
    lines.append("omega " + " ".join(f"{x:.17g}" for x in omega_si))
    (data / "pyslfp_fingerprint.txt").write_text("\n".join(lines) + "\n")
    print("wrote pyslfp_generalised_sea_level.txt and pyslfp_fingerprint.txt")
    print(f"gate A omega_si {omega_si}")


if __name__ == "__main__":
    main()
