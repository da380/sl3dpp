#pragma once

/**
 * @file detail/TrajectoryCursor.hpp
 * @brief The forward states of a recorded 1D run, served to the
 * derivative runs about it: the reverse sweeps (first and second order,
 * discrete and continuous, the lateral kernels' among them) and the
 * tangent-linear runs. Implementation detail.
 */

#include <complex>
#include <cstddef>
#include <deque>
#include <functional>
#include <vector>

#include "sl3dpp/Adjoint.hpp"
#include "sl3dpp/Viscoelastic.hpp"

namespace sl3dpp::detail {

/**
 * @brief Serves the forward internal states of a recorded run, with their
 * strain, in either direction.
 *
 * A kept state is the recording's, its strain regenerated by one elastic
 * solve under its node's recorded loads unless kept with it. A state
 * between two kept ones is rebuilt by the run's own steps forward from the
 * kept state below: the same scheme and step sizes, each step finished
 * under its end node's recorded total-load and centrifugal coefficients,
 * which are what the run's radial step consumed (the sea level solve, a
 * migrating run's ocean functions, the rotation and a tide reach it only
 * through them; the two nodes of a jump are a step of zero length between
 * their recorded sides). Forward steps damp, so a rebuilt state is the
 * run's to rounding at any stride. What that needs of the recording: the
 * first node's state and every node's coefficients, which a run with
 * record_stride keeps. A step of a multi-stage scheme closes its first
 * stage under the forcing at its own time, which the recording does not
 * hold, and a recording with gaps is refused under one; a run under
 * interior sources is recorded at every node (Evolution::Forcing).
 *
 * A request below what is held (a reverse sweep entering a gap) rebuilds
 * from the kept state at or below the node up to it and holds those
 * states until the sweep has passed below them: one gap at a time, so a
 * reverse sweep holds the kept states and at most a stride's worth more.
 * A request above advances forwards, holding the newest two. A request
 * may step through the flavours of a gap's step sizes, evicting others
 * from the operator's cache; a flavour a caller holds, and what it owns,
 * stays alive, its ownership shared (ViscoelasticOperator::FlavourOf).
 */
class TrajectoryCursor {
 public:
  /// A node's recorded coefficients as the operator's load channel.
  using ChannelOf =
      std::function<LoadCallable(const std::vector<std::complex<double>>&)>;

  /// `dts` the material-unit step sizes of the time grid; the trajectory
  /// keeps its first node's state and gives every node's coefficients (the
  /// sweeps' argument checks).
  TrajectoryCursor(const ViscoelasticOperator& op,
                   const ForwardTrajectory& trajectory, std::vector<double> dts,
                   Scheme scheme, ChannelOf loadOf, ChannelOf tideOf);

  /// The forward state at a node, with its strain; the reference stays
  /// valid until the next call.
  [[nodiscard]] const ViscoelasticState& State(std::size_t node);

 private:
  [[nodiscard]] std::size_t Last() const { return first_ + held_.size() - 1; }
  /// The kept state at a node, its strain regenerated where not kept.
  [[nodiscard]] ViscoelasticState Kept(std::size_t node) const;
  /// Steps from the newest held state up to the node; `hold` keeps every
  /// state stepped, else the newest two.
  void Advance(std::size_t node, bool hold);

  const ViscoelasticOperator* op_;
  const ForwardTrajectory* trajectory_;
  std::vector<double> dts_;
  Scheme scheme_;
  ChannelOf loadOf_, tideOf_;
  /// The held states, of the nodes first_, first_ + 1, ... .
  std::size_t first_ = 0;
  std::deque<ViscoelasticState> held_;
};

}  // namespace sl3dpp::detail
